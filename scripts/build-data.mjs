// Converts the reference tables in data/raw into importable ES modules under src/data.
// Run with `npm run data` after changing anything in data/raw.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const raw = (f) => readFile(resolve(root, "data/raw", f), "utf8");

const XCOM = {
  water: { file: "xcom-water.csv", name: "Water, liquid", density: 1.0 },
  tissue: { file: "xcom-tissue.csv", name: "Tissue, soft (ICRU-44)", density: 1.06 },
  bone: { file: "xcom-bone.csv", name: "Bone, cortical (ICRU-44)", density: 1.92 },
  lead: { file: "xcom-lead.csv", name: "Lead", density: 11.35 },
  zinc: { file: "xcom-zinc.csv", name: "Zinc", density: 7.134 },
  pyrex: { file: "xcom-pyrex.csv", name: "Glass, borosilicate (Pyrex)", density: 2.23 },
};
const xcom = {};
for (const [key, m] of Object.entries(XCOM)) {
  const text = await raw(m.file);
  const url = text.match(/https:\/\/\S+/)[0];
  const rows = text
    .split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => l.split(",").map(Number));
  xcom[key] = { name: m.name, density: m.density, source: url, rows };
}
await writeFile(
  resolve(root, "src/data/xcom.js"),
  "// Generated by scripts/build-data.mjs from NIST X-Ray Mass Attenuation Coefficients\n" +
    "// (Hubbell & Seltzer, NISTIR 5632), retrieved 2026-10-03. rows: [energy MeV, mu/rho cm^2/g].\n" +
    "// Repeated energies mark absorption edges (below, then above).\n" +
    "export const XCOM = " + JSON.stringify(xcom) + ";\n",
);

const seg = (await raw("segelstein81.dat"))
  .split("\n")
  .map((l) => l.trim().split(/\s+/).map(Number))
  .filter((r) => r.length === 2 && r.every(Number.isFinite));
await writeFile(
  resolve(root, "src/data/water.js"),
  "// Generated by scripts/build-data.mjs from D. J. Segelstein, \"The complex refractive index of water\",\n" +
    "// M.S. thesis, University of Missouri-Kansas City (1981), via https://omlc.org/spectra/water/ (retrieved 2026-10-03).\n" +
    "// rows: [vacuum wavelength nm, absorption coefficient 1/cm], 10 nm to 10 m.\n" +
    "export const WATER_ABSORPTION = " + JSON.stringify(seg) + ";\n",
);
console.log(`xcom: ${Object.keys(xcom).length} materials; water: ${seg.length} rows`);
